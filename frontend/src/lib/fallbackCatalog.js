function buildUpcomingSchedule(times) {
  const out = {};
  for (let i = 1; i <= 6; i += 1) {
    const d = new Date();
    d.setDate(d.getDate() + i);
    out[d.toISOString().slice(0, 10)] = times;
  }
  return out;
}

